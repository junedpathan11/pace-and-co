import type { Product, ProductVariant, Stock } from "./types";

/* -----------------------------------------------------------
   Variant helpers — keep the data source terse but explicit.
   ----------------------------------------------------------- */
function variants(
  sizes: string[],
  colors: string[],
  outCombos: string[] = [], // "size|color" that are out of stock
  lowCombos: string[] = []
): ProductVariant[] {
  const out: ProductVariant[] = [];
  for (const color of colors) {
    for (const size of sizes) {
      const key = `${size}|${color}`;
      let stock: Stock = "in_stock";
      if (outCombos.includes(key)) stock = "out";
      else if (lowCombos.includes(key)) stock = "low";
      out.push({ size, color, stock });
    }
  }
  return out;
}

