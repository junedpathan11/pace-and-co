/* -----------------------------------------------------------
   Derived helpers / data-layer functions (backend-swappable)
   ----------------------------------------------------------- */
export function getAllProducts(): Product[] {
  return products;
}

export function getProductBySlug(slug: string): Product | undefined {
  return products.find((p) => p.slug === slug);
}

export function getProductsByType(type: Product["productType"]): Product[] {
  return products.filter((p) => p.productType === type);
}

export function getSaleProducts(): Product[] {
  return products.filter((p) => p.badge === "sale" || p.compareAtPrice);
}

export function getNewProducts(): Product[] {
  return products.filter((p) => p.badge === "new");
}

export function getSizesForProduct(p: Product): string[] {
  return Array.from(new Set(p.variants.map((v) => v.size)));
}

export function getColorsForProduct(p: Product): string[] {
  return Array.from(new Set(p.variants.map((v) => v.color)));
}

export function isVariantAvailable(p: Product, size: string, color: string): boolean {
  const v = p.variants.find((x) => x.size === size && x.color === color);
  return !!v && v.stock !== "out";
}

export function getVariant(p: Product, size: string, color: string) {
  return p.variants.find((x) => x.size === size && x.color === color);
}

export function discountPercent(p: Product): number | null {
  if (!p.compareAtPrice || p.compareAtPrice <= p.price) return null;
  return Math.round(((p.compareAtPrice - p.price) / p.compareAtPrice) * 100);
}
